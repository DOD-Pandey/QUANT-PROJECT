# Change span from 20 to 14
df['EMA'] = df[('Close', 'SPY')].ewm(span=14, adjust=False).mean()

# 1. Get the daily price change
df['Price_Change'] = df[('Close', 'SPY')].diff()

# 2. Separate gains from losses
df['Gain'] = np.where(df['Price_Change'] > 0, df['Price_Change'], 0)
df['Loss'] = np.where(df['Price_Change'] < 0, -df['Price_Change'], 0)

# 3. Calculate the 14-day rolling average of gains and losses
roll_gain = df['Gain'].rolling(window=14).mean()
roll_loss = df['Loss'].rolling(window=14).mean()

# 4. Calculate the Relative Strength (RS) and scale it between 0 and 100 (RSI)
RS = roll_gain / roll_loss
df['RSI'] = 100 - (100 / (1 + RS))

# Drop NaN values generated by the 14-day lookback window
df.dropna(inplace=True)

# Initialize a column of zeros (0 = Hold / Cash)
df['Signal'] = 0

# Apply the updated, relaxed Entry Condition (BUY = 1)
# We allow buying even if RSI is up to 80 now!
buy_condition = (df[('Close', 'SPY')] > df['EMA']) & (df['RSI'] < 80)
df.loc[buy_condition, 'Signal'] = 1

# Apply the updated, relaxed Exit Condition (SELL = 0)
# We hold onto the asset until RSI screams past 80!
exit_condition = (df[('Close', 'SPY')] < df['EMA']) | (df['RSI'] > 80)
df.loc[exit_condition, 'Signal'] = 0

# 1. Shift signals by 1 day 
# (Because you generate a signal at today's close, you capture tomorrow's return!)
df['Strategy_Signal'] = df['Signal'].shift(1)

# 2. Calculate Strategy Log Returns
# If signal is 1, you get the market return. If signal is 0, you get 0% (cash).
df['Strategy_Return'] = df['Strategy_Signal'] * df['Log_Return']

# 3. Compute your custom Strategy Performance Metrics
strat_annualized_return = df['Strategy_Return'].mean() * 252
strat_annualized_vol = df['Strategy_Return'].std() * np.sqrt(252)
strat_sharpe = strat_annualized_return / strat_annualized_vol

# Print out the ultimate comparative report
print("\n" + "="*60)
print(f"        QUANT PERFORMANCE REPORT: {TICKER} vs STRATEGY")
print("="*60)
print(f"METRIC               BUY-AND-HOLD       EMA+RSI STRATEGY")
print("-"*60)
print(f"Annualized Return:     {annualized_return * 100:.2f}%             {strat_annualized_return * 100:.2f}%")
print(f"Annualized Volatility: {annualized_volatility * 100:.2f}%             {strat_annualized_vol * 100:.2f}%")
print(f"Annualized Sharpe:     {annualized_sharpe:.2f}               {strat_sharpe:.2f}")
print("="*60 + "\n")
